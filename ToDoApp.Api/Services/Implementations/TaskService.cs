using ToDoApp.Api.Data;
using ToDoApp.Api.Models;
using ToDoApp.Api.Services.Interfaces;
using Microsoft.EntityFrameworkCore;
using ToDoApp.Api.Common;
using ToDoApp.Api.Dtos;

namespace ToDoApp.Api.Services.Implementations
{
    public class TaskService : ITaskService
    {
        private readonly AppDbContext _appDbContext;
        private readonly ILogger<TaskService> _logger;

        public TaskService(AppDbContext appDbContext, ILogger<TaskService> logger)
        {
            _appDbContext = appDbContext;
            _logger = logger;
        }

        public async Task<ServiceResult<List<TaskItem>>> GetTasks(Guid userId)
        {
            var taskList =  await _appDbContext.Tasks.Where(t => t.UserId == userId).ToListAsync();

            return ServiceResult<List<TaskItem>>.Ok(taskList);
        }

        public async Task<ServiceResult<TaskItem>> PostTask(CreateTaskRequest request, Guid userId)
        {

            if (userId == Guid.Empty)
            {
                return ServiceResult<TaskItem>.Fail("A valid user is required.", ServiceErrorType.ValidationFailed);
            }

            if (string.IsNullOrWhiteSpace(request.TaskDescription))
            {
                return ServiceResult<TaskItem>.Fail("Task description cannot be empty.", ServiceErrorType.ValidationFailed);
            }

            if (request.TaskDescription.Length > 1000)
            {
                return ServiceResult<TaskItem>.Fail("Task description cannot exceed 1000 characters.", ServiceErrorType.ValidationFailed);
            }

            var taskItem = new TaskItem
            {
                // TaskItemId and RowVersion are generated by the database.
                UserId = userId,
                TaskDescription = request.TaskDescription,
                IsCompleted = false
            };

            await _appDbContext.Tasks.AddAsync(taskItem);

            await _appDbContext.SaveChangesAsync();

            return ServiceResult<TaskItem>.Ok(taskItem);
        }

        public async Task<ServiceResult<TaskItem>> ModifyTask(int id, ModifyTaskRequest request, Guid userId)
        {
            var task = await _appDbContext.Tasks.FindAsync(id);

            if (task is null)
            {
                return ServiceResult<TaskItem>.Fail("Task not found.", ServiceErrorType.NotFound);
            }

            if (task.UserId != userId)
            {
                // Not reachable from the app, so unusual, but handled: Warning rather than Error.
                _logger.LogWarning("User {UserId} attempted to modify task {TaskId}, " +
                    "which belongs to another user. Request rejected.", userId, id);
                return ServiceResult<TaskItem>.Fail("Task not found.", ServiceErrorType.NotFound);
            }

            if (string.IsNullOrWhiteSpace(request.TaskDescription))
            {
                return ServiceResult<TaskItem>.Fail("Task description cannot be empty.", ServiceErrorType.ValidationFailed);
            }

            // Compare against the version the client saw, not the one FindAsync just loaded;
            // otherwise conflicts are never detected.
            _appDbContext.Entry(task).Property(t => t.RowVersion).OriginalValue = request.RowVersion;

            task.TaskDescription = request.TaskDescription;

            task.IsCompleted = request.IsCompleted;

            try 
            {
                await _appDbContext.SaveChangesAsync();
            }
            catch(DbUpdateConcurrencyException)
            {
                _logger.LogWarning("Task {TaskId} was already updated by someone else. " +
                    "The save attempt by user {UserId} was rejected to avoid overwriting their changes.", id, userId);
                return ServiceResult<TaskItem>.Fail("Task was modified meanwhile.", ServiceErrorType.Conflict);
            }


            return ServiceResult<TaskItem>.Ok(task);
        }

        public async Task<ServiceResult> DeleteTask(int id, Guid userId, uint rowVersion)
        {
            var task = await _appDbContext.Tasks.FindAsync(id);

            if (task is null)
            {
                return ServiceResult.Fail("Task not found.", ServiceErrorType.NotFound);
            }

            if (task.UserId != userId)
            {
                _logger.LogWarning("User {UserId} attempted to delete task {TaskId}, " +
                    "which belongs to another user. Request rejected.", userId, id);
                return ServiceResult.Fail("Task not found.", ServiceErrorType.NotFound);
            }

            _appDbContext.Entry(task).Property(t => t.RowVersion).OriginalValue = rowVersion;

            _appDbContext.Tasks.Remove(task);

            try
            {
                await _appDbContext.SaveChangesAsync();
            }
            catch (DbUpdateConcurrencyException)
            {
                // Not reachable from the app, so unusual, but handled: Warning rather than Error.
                _logger.LogWarning("Task {TaskId} was already updated by someone else. " +
                    "The delete attempt by user {UserId} was rejected to avoid discarding their changes.", id, userId);
                return ServiceResult<TaskItem>.Fail("Task was modified meanwhile.", ServiceErrorType.Conflict);
            }

            return ServiceResult.Ok();
        }
    }
}
